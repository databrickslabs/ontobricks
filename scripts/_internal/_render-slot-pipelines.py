#!/usr/bin/env python3
"""Render ``resources/_generated_triple_slots.yml``: the slot pipelines DAB deploys.

One Lakeflow pipeline resource per **published** domain version whose
requested materialization mode is ``incremental``, ``microbatch`` or
``realtime`` and whose mappings compile into at least one row-local slot
flow. Called by ``scripts/deploy.sh`` right before ``databricks bundle
validate``; the file is gitignored and picked up by ``include:
resources/*.yml``.

The resource is exactly what ``SlotPipelineRunner.ensure`` would create —
same name (``SlotPipelineRunner.pipeline_name``, so the runner finds the
deployed pipeline by name and only creates one when it is absent), catalog /
schema (``TwinIncrementalBuild.compile_for``), serverless, channel, never in
development mode, continuous for ``microbatch`` / ``realtime`` — with three
rules that keep DAB and the runner from fighting:

* the library is the SQL file the runner uploads at build time
  (``/Workspace/Users/<app principal>/.ontobricks/pipelines/<name>.sql``);
* the ``ontobricks.slot_sql_sha256`` fingerprint is the one the deployed
  pipeline already carries (``""`` for a new one): DAB never stamps a
  fingerprint for SQL the pipeline has not run, which would skip the full
  refresh a mapping change needs;
* the app principal gets ``CAN_MANAGE`` so the runner can update and run it.

Nothing is rendered, and an existing file is **kept as it is**, when the
registry or the workspace cannot be reached or the app principal is unknown:
removing the file would make ``bundle deploy`` delete every pipeline it
deployed before (and its ``_slots`` streaming table). For the same reason a
version whose mappings no longer compile keeps its previously rendered
resource (with a notice). A version that stops being published, or a domain
switched to ``full``, drops out of the file and its pipeline is deleted by the
next deploy.

A deployed pipeline is found under its name or, deployed by a bundle in
development mode, ``[dev <user>] <name>`` (with a notice: the dev targets set
``presets: {name_prefix: "", pipelines_development: false}`` so the bundle and
the runner agree on the name). A pipeline the app's runner created before the
bundle managed it (same name, no bundle deployment metadata) is listed in
``_generated_triple_slots.bind``
(``<resource key> <pipeline id>`` per line): ``scripts/deploy.sh`` binds it to
its resource before ``bundle deploy``, which would otherwise create a second
pipeline on the same ``_slots`` table. A pipeline another bundle manages is
never listed.

Environment: ``REGISTRY_CATALOG``, ``REGISTRY_SCHEMA``, ``REGISTRY_VOLUME``,
``LAKEBASE_SCHEMA``, ``LAKEBASE_DATABASE`` (+ the ``PG*`` connection env),
``APP_SP_CLIENT_ID``. Exit status 0 when rendered or skipped (a notice on
stderr); a file that cannot be written fails the script.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Any

import yaml

REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT = REPO_ROOT / "resources/_generated_triple_slots.yml"
_BIND_SUFFIX = ".bind"
_HEADER = (
    "# AUTO-GENERATED by scripts/_internal/_render-slot-pipelines.py — do not edit.\n"
    "# One slot pipeline per published incremental / microbatch / realtime domain\n"
    "# version; regenerated by every scripts/deploy.sh run (kept when the registry\n"
    "# is unreachable).\n"
)
_KEY_CHARS = re.compile(r"[^a-z0-9_]+")
_STREAMING_MODES = ("incremental", "microbatch", "realtime")
_CONTINUOUS_MODES = ("microbatch", "realtime")


class SlotPipelineBundle:
    """Collect the published incremental domain versions and render their pipeline resources."""

    @staticmethod
    def resource_key(name: str) -> str:
        """A DAB resource key for pipeline *name* (``ontobricks_slots_<dom>_v<n>``)."""
        return _KEY_CHARS.sub("_", name.lower()).strip("_")

    @staticmethod
    def pipeline_resource(
        *,
        name: str,
        slots_fqn: str,
        continuous: bool,
        channel: str,
        app_principal: str,
        stored_fingerprint: str,
    ) -> dict:
        """The resource ``SlotPipelineRunner.ensure`` would create for *name*."""
        from back.core.streaming import SlotPipelineRunner

        catalog, schema, _ = slots_fqn.split(".", 2)
        return {
            "name": name,
            "catalog": catalog,
            "schema": schema,
            "serverless": True,
            "continuous": bool(continuous),
            "channel": channel,
            "development": False,
            "libraries": [
                {
                    "file": {
                        "path": f"/Workspace/Users/{app_principal}/.ontobricks/pipelines/{name}.sql"
                    }
                }
            ],
            "configuration": {SlotPipelineRunner.FINGERPRINT_KEY: stored_fingerprint},
            "permissions": [{"service_principal_name": app_principal, "level": "CAN_MANAGE"}],
        }

    @staticmethod
    def collect(
        svc: Any,
        settings: Any,
        runner: Any,
        *,
        app_principal: str,
        load_domain: Callable[[Any, str, str], Any],
        notice: Callable[[str], None] = print,
        previous: dict | None = None,
    ) -> dict:
        """``{resource key: pipeline resource}`` of every eligible published domain version.

        *previous* is the last rendered map: a version whose mappings no longer
        compile keeps its resource from it, so the deploy never deletes its
        pipeline on a compile error.
        """
        from back.core.errors import ValidationError
        from back.core.graphdb.GraphDBFactory import (
            GraphDBFactory,
            normalize_materialization_mode,
        )
        from back.core.streaming import SlotPipelineRunner
        from back.objects.digitaltwin.build import TwinIncrementalBuild, TwinSlotPipeline

        ok, folders, message = svc.list_domains()
        if not ok:
            raise RuntimeError(f"Could not list the registry domains: {message}")
        resources: dict = {}
        for folder in folders:
            version, _data = svc.find_published_version(folder)
            if not version:
                continue
            domain = load_domain(svc, folder, version)
            mode = normalize_materialization_mode(
                GraphDBFactory.resolve_materialization_mode(domain, settings)
            )
            mappings = TwinIncrementalBuild.mappings_for(domain)
            if mode not in _STREAMING_MODES or mappings is None:
                continue
            entities, relationships, base_uri = mappings
            name = SlotPipelineRunner.pipeline_name((domain.info or {}).get("name", folder), version)
            key = SlotPipelineBundle.resource_key(name)
            try:
                spec = TwinIncrementalBuild.compile_for(
                    domain, settings, entities, relationships, base_uri=base_uri
                )
            except ValidationError as exc:
                if key in (previous or {}):
                    notice(f"keep the previous {key}: {folder} v{version} mappings do not compile ({exc})")
                    resources[key] = previous[key]
                else:
                    notice(f"skip {folder} v{version}: the mappings do not compile ({exc})")
                continue
            if not spec.row_local_map_ids:
                continue
            found = runner.find_pipeline(name)
            pipeline_id = found[0] if found else None
            if found and found[1] != name:
                notice(
                    f"{found[1]!r} carries a development-mode prefix: set the target's presets "
                    "name_prefix: '' and pipelines_development: false (docs: DAB deployment)"
                )
            resources[key] = SlotPipelineBundle.pipeline_resource(
                name=name,
                slots_fqn=spec.slots_fqn,
                continuous=mode in _CONTINUOUS_MODES,
                channel=TwinSlotPipeline.channel(settings),
                app_principal=app_principal,
                stored_fingerprint=runner.stored_fingerprint(pipeline_id) if pipeline_id else "",
            )
        return resources

    @staticmethod
    def bindings(resources: dict, runner: Any) -> list[tuple[str, str]]:
        """``(resource key, pipeline id)`` of each rendered pipeline that exists outside any bundle."""
        bindings = []
        for key, resource in sorted(resources.items()):
            pipeline_id = runner.find_pipeline_id(resource["name"])
            if pipeline_id and not runner.bundle_managed(pipeline_id):
                bindings.append((key, pipeline_id))
        return bindings

    @staticmethod
    def previous_resources(output: Path) -> dict:
        """The pipeline map of the file rendered last time (``{}`` when absent or unreadable)."""
        try:
            loaded = yaml.safe_load(output.read_text(encoding="utf-8")) or {}
        except (OSError, yaml.YAMLError):
            return {}
        pipelines = (loaded.get("resources") or {}).get("pipelines") if isinstance(loaded, dict) else None
        return pipelines if isinstance(pipelines, dict) else {}

    @staticmethod
    def render(resources: dict) -> str:
        """The YAML of ``resources/_generated_triple_slots.yml`` for *resources*."""
        body = yaml.safe_dump(
            {"resources": {"pipelines": dict(sorted(resources.items()))}},
            sort_keys=False,
            default_flow_style=False,
        )
        return _HEADER + body

    @staticmethod
    def registry_service() -> Any:
        """The Lakebase registry the deploy env points at (``KeyError`` when it is unset)."""
        from back.objects.registry.RegistryService import RegistryCfg, RegistryService

        cfg = RegistryCfg(
            catalog=os.environ["REGISTRY_CATALOG"],
            schema=os.environ["REGISTRY_SCHEMA"],
            volume=os.environ.get("REGISTRY_VOLUME", "") or "OntoBricksRegistry",
            lakebase_schema=os.environ["LAKEBASE_SCHEMA"],
            lakebase_database=os.environ["LAKEBASE_DATABASE"],
        )
        return RegistryService(cfg, None)

    @staticmethod
    def load_domain(svc: Any, folder: str, version: str) -> Any:
        from back.objects.registry.schedule.TaskContext import load_domain_headless

        domain, _ = load_domain_headless(svc, folder, version, "", {})
        return domain


def main(
    argv: list[str] | None = None,
    *,
    svc_factory: Callable[[], Any] | None = None,
    runner_factory: Callable[[], Any] | None = None,
    settings: Any = None,
) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", default=str(OUTPUT))
    args = parser.parse_args(argv)
    output = Path(args.output)
    bind_file = output.with_suffix(_BIND_SUFFIX)
    # A bind list is only valid for the render that produced it.
    bind_file.unlink(missing_ok=True)

    def notice(message: str) -> None:
        print(f"render-slot-pipelines: {message}", file=sys.stderr)

    app_principal = (os.environ.get("APP_SP_CLIENT_ID") or "").strip()
    if not app_principal:
        notice("APP_SP_CLIENT_ID is unknown; slot pipelines not rendered (previous file kept)")
        return 0
    try:
        from back.core.streaming import SlotPipelineRunner
        from shared.config.settings import get_settings

        svc = (svc_factory or SlotPipelineBundle.registry_service)()
        runner = (runner_factory or SlotPipelineRunner)()
        resources = SlotPipelineBundle.collect(
            svc,
            settings if settings is not None else get_settings(),
            runner,
            app_principal=app_principal,
            load_domain=SlotPipelineBundle.load_domain,
            notice=notice,
            previous=SlotPipelineBundle.previous_resources(output),
        )
        bindings = SlotPipelineBundle.bindings(resources, runner)
    except Exception as exc:  # noqa: BLE001 — unreachable registry / workspace: keep the file
        notice(f"registry or workspace unreachable ({exc}); previous file kept")
        return 0
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(SlotPipelineBundle.render(resources), encoding="utf-8")
    bind_file.write_text("".join(f"{key} {pid}\n" for key, pid in bindings), encoding="utf-8")
    notice(f"{len(resources)} slot pipeline(s) rendered into {output}, {len(bindings)} to bind")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
